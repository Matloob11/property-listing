const browseCache = new Map();

function sortUnique(items) {
  return [...new Set((items || []).map((item) => String(item || "").trim()).filter(Boolean))].sort((a, b) =>
    a.localeCompare(b)
  );
}

export function emptyCatalog() {
  return { cities: [], communities: {}, sub_communities: {} };
}

export function addLocation(catalog, { city, community, sub_community } = {}) {
  const next = catalog || emptyCatalog();
  const place = String(city || "").trim();
  if (!place) return next;
  if (!next.communities[place]) next.communities[place] = [];
  if (!next.sub_communities[place]) next.sub_communities[place] = {};
  if (!next.cities.includes(place)) next.cities.push(place);
  const comm = String(community || "").trim();
  if (comm) {
    if (!next.communities[place].includes(comm)) next.communities[place].push(comm);
    if (!next.sub_communities[place][comm]) next.sub_communities[place][comm] = [];
    const sub = String(sub_community || "").trim();
    if (sub && !next.sub_communities[place][comm].includes(sub)) {
      next.sub_communities[place][comm].push(sub);
    }
  }
  return next;
}

export function mergeCatalogs(...catalogs) {
  const next = emptyCatalog();
  for (const catalog of catalogs) {
    for (const city of catalog?.cities || []) addLocation(next, { city });
    for (const [city, comms] of Object.entries(catalog?.communities || {})) {
      for (const community of comms || []) addLocation(next, { city, community });
    }
    for (const [city, groups] of Object.entries(catalog?.sub_communities || {})) {
      for (const [community, subs] of Object.entries(groups || {})) {
        addLocation(next, { city, community });
        for (const sub of subs || []) addLocation(next, { city, community, sub_community: sub });
      }
    }
  }
  next.cities = sortUnique(next.cities);
  for (const city of next.cities) {
    next.communities[city] = sortUnique(next.communities[city]);
    next.sub_communities[city] = next.sub_communities[city] || {};
    for (const community of Object.keys(next.sub_communities[city])) {
      next.sub_communities[city][community] = sortUnique(next.sub_communities[city][community]);
    }
  }
  return next;
}

export function catalogFromSeed() {
  const next = emptyCatalog();
  for (const [city, groups] of Object.entries(LOCATIONS)) {
    for (const [community, subs] of Object.entries(groups)) {
      addLocation(next, { city, community });
      for (const sub of subs || []) addLocation(next, { city, community, sub_community: sub });
    }
  }
  for (const [city, comms] of Object.entries(EXTRA_COMMUNITIES)) {
    for (const community of comms) addLocation(next, { city, community });
  }
  return mergeCatalogs(next);
}

export function catalogFromListings(rows) {
  const next = emptyCatalog();
  for (const row of rows || []) {
    addLocation(next, {
      city: row.city || row.bayut_city,
      community: row.community || row.bayut_community,
      sub_community: row.sub_community || row.bayut_sub_community,
    });
  }
  return mergeCatalogs(next);
}

export function catalogFromPfRows(rows) {
  const next = emptyCatalog();
  for (const row of rows || []) {
    const tree = Array.isArray(row.tree) ? row.tree : [];
    const city = tree.find((node) => node.type === "CITY")?.name || "";
    const community = tree.find((node) => node.type === "COMMUNITY")?.name || (row.type === "COMMUNITY" ? row.name : "");
    const sub = tree.find((node) => node.type === "SUBCOMMUNITY")?.name || (row.type === "SUBCOMMUNITY" ? row.name : "");
    addLocation(next, { city, community, sub_community: sub });
  }
  return mergeCatalogs(next);
}

export function locationCatalog() {
  return catalogFromSeed();
}

export function countCatalog(catalog) {
  const communities = Object.values(catalog?.communities || {}).reduce((n, rows) => n + rows.length, 0);
  let subs = 0;
  for (const groups of Object.values(catalog?.sub_communities || {})) {
    for (const rows of Object.values(groups || {})) subs += rows.length;
  }
  return { cities: catalog?.cities?.length || 0, communities, subs };
}

export function hitFromParts(parts, extra = {}) {
  const city = String(parts.city || "").trim();
  const community = String(parts.community || "").trim();
  const sub = String(parts.sub_community || "").trim();
  const building = String(parts.building || "").trim();
  const path = [city, community, sub, building].filter(Boolean).join(" - ");
  return {
    id: String(extra.id || parts.id || ""),
    name: String(extra.name || building || sub || community || city),
    type: String(extra.type || parts.type || ""),
    path,
    city,
    community,
    sub_community: sub,
    building,
    latitude: String(parts.latitude || extra.latitude || ""),
    longitude: String(parts.longitude || extra.longitude || ""),
  };
}

export function localLocationHits(catalog, { q = "", city = "", community = "", type = "" } = {}) {
  const needle = String(q || "").trim().toLowerCase();
  const hits = [];
  const cities = city ? [city] : catalog.cities || [];
  for (const place of cities) {
    if (!type || type === "CITY") {
      if (!needle || place.toLowerCase().includes(needle)) {
        hits.push(hitFromParts({ city: place }, { type: "CITY", name: place }));
      }
    }
    for (const comm of catalog.communities?.[place] || []) {
      if (community && comm !== community) continue;
      if (!type || type === "COMMUNITY") {
        if (!needle || comm.toLowerCase().includes(needle)) {
          hits.push(hitFromParts({ city: place, community: comm }, { type: "COMMUNITY", name: comm }));
        }
      }
      for (const sub of catalog.sub_communities?.[place]?.[comm] || []) {
        if (!type || type === "SUBCOMMUNITY" || type === "TOWER") {
          if (!needle || sub.toLowerCase().includes(needle)) {
            hits.push(
              hitFromParts(
                { city: place, community: comm, sub_community: type === "TOWER" ? "" : sub, building: type === "TOWER" ? sub : "" },
                { type: type || "SUBCOMMUNITY", name: sub }
              )
            );
          }
        }
      }
    }
  }
  return hits.slice(0, 40);
}

function sameHit(a, b) {
  return (a.id && b.id && a.id === b.id) || (a.path && a.path === b.path);
}

export function dedupeHits(hits) {
  const out = [];
  for (const hit of hits || []) {
    if (!hit?.path && !hit?.name) continue;
    if (out.some((row) => sameHit(row, hit))) continue;
    out.push(hit);
  }
  return out;
}

export async function fullLocationCatalog(db) {
  const listings = db?.all ? await db.all() : [];
  const pfRows = db?.pfLocations ? await db.pfLocations() : [];
  return mergeCatalogs(catalogFromSeed(), catalogFromListings(listings), catalogFromPfRows(pfRows));
}

function browseSeeds(city) {
  const name = String(city || "").toLowerCase();
  const seeds = ["al", "ar", "ma", "ba"];
  if (name.includes("dubai")) seeds.push("du", "ju", "th", "vi", "se", "pa", "em", "hi");
  else seeds.push(name.slice(0, 2), "sa", "kh", "ya");
  return sortUnique(seeds.filter((item) => item.length >= 2));
}

async function mapPool(items, size, worker) {
  const queue = [...items];
  const runners = Array.from({ length: Math.min(size, queue.length) }, async () => {
    while (queue.length) {
      const item = queue.shift();
      await worker(item);
    }
  });
  await Promise.all(runners);
}

export async function browseCityCatalog(city) {
  const place = String(city || "").trim();
  const cached = browseCache.get(place);
  if (cached && Date.now() - cached.at < 6 * 60 * 60 * 1000) return cached.catalog;
  const catalog = emptyCatalog();
  addLocation(catalog, { city: place });
  try {
    const { locationParts, pfConfigured, searchLocations } = await import("./pf.js");
    if (place && pfConfigured()) {
      await mapPool(browseSeeds(place), 3, async (seed) => {
        try {
          const rows = await searchLocations(seed, { type: "COMMUNITY", parent: place, perPage: 100 });
          for (const row of rows) addLocation(catalog, locationParts(row));
        } catch {
          /* keep local catalog if one seed fails */
        }
      });
    }
  } catch {
    /* Property Finder browse is optional */
  }
  const next = mergeCatalogs(catalog);
  browseCache.set(place, { at: Date.now(), catalog: next });
  return next;
}

export async function searchLocationHits({ q, city, community, type, catalog } = {}) {
  const query = String(q || "").trim();
  const local = localLocationHits(catalog || catalogFromSeed(), { q: query, city, community, type });
  let remote = [];
  if (query.length >= 2) {
    try {
      const { locationParts, pfConfigured, searchLocations } = await import("./pf.js");
      if (pfConfigured()) {
        const parent = [city, community].filter(Boolean).join(", ");
        const rows = await searchLocations(query, {
          type: type || undefined,
          parent: parent || undefined,
          perPage: 50,
        });
        remote = rows.map((row) => hitFromParts(locationParts(row), { id: row.id, name: row.name, type: row.type }));
      }
    } catch {
      remote = [];
    }
  }
  return dedupeHits([...remote, ...local]).slice(0, 40);
}
